# ==========================================
# SUPERVISED vs UNSUPERVISED LEARNING
# ==========================================

# 1. SUPERVISED LEARNING
# ----------------------
# Training data contains:
# X = Features/Input
# y = Target/Label/Correct Output
#
# Model learns the relationship between X and y
# and predicts the output for new/unseen data.

# Types:
# Regression     -> Predict numerical values
# Classification -> Predict categories/classes

# Examples:
# House data -> House Price       (Regression)
# Email -> Spam / Not Spam        (Classification)
# Image -> Cat / Dog              (Classification)

# Algorithms:
# Linear Regression
# Logistic Regression
# Decision Tree
# Random Forest
# KNN
# SVM


# 2. UNSUPERVISED LEARNING
# ------------------------
# Training data contains only:
# X = Features/Input
# No target/label is provided.
#
# Model discovers hidden patterns,
# structures, or groups in the data.

# Common Tasks:
# Clustering -> Create groups of similar data
# Dimensionality Reduction -> Reduce number of features

# Examples:
# Customer data -> Customer Groups
# Similar products -> Product Groups

# Algorithms:
# K-Means
# Hierarchical Clustering
# DBSCAN
# PCA


# ==========================================
# KEY DIFFERENCE
# ==========================================

# Supervised:
# Data + Labels -> Learn -> Predict

# Unsupervised:
# Data only -> Discover Patterns/Groups


# REMEMBER:
# Supervised     = Label available
# Unsupervised   = No label
#
# Regression     = Number
# Classification = Category
# Clustering     = Groups