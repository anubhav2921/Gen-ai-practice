# =========================
# MACHINE LEARNING - NOTES
# =========================

# Machine Learning:
# Data se patterns learn karke prediction/decision karna.

# Dataset:
# Data ka collection jisme features aur target hote hain.

# Feature (X):
# Input variable used to make predictions.

# Target / Label (y):
# Output that we want the model to predict.


# =========================
# TYPES OF MACHINE LEARNING
# =========================

# 1. Supervised Learning:
# Input + Correct Output (Label) available hota hai.

# Regression:
# Numerical/continuous value predict karta hai.
# Example: House Price, Marks, Temperature

# Classification:
# Category/Class predict karta hai.
# Example: Spam/Not Spam, Cat/Dog


# 2. Unsupervised Learning:
# Target/Label nahi hota.
# Model data ke hidden patterns/groups find karta hai.

# Clustering:
# Similar data points ko groups mein divide karta hai.
# Example: K-Means


# =========================
# ML WORKFLOW
# =========================

# 1. Collect Dataset
# 2. Clean & Preprocess Data
# 3. Select Features (X) and Target (y)
# 4. Split Data into Train & Test
# 5. Train the Model
# 6. Evaluate the Model
# 7. Make Predictions


# =========================
# IMPORTANT TERMS
# =========================

# model.fit(X, y)
# Model ko data se train/learn karata hai.

# model.predict(X_new)
# New/unseen data par prediction karta hai.

# Train Data:
# Model ko patterns learn karne ke liye use hota hai.

# Test Data:
# Model ki performance check karne ke liye use hota hai.

# Common Split:
# 80% Training + 20% Testing


# =========================
# IMPORTANT ALGORITHMS
# =========================

# Regression:
# Linear Regression

# Classification:
# Logistic Regression
# Decision Tree
# Random Forest
# KNN
# SVM

# Unsupervised:
# K-Means
# PCA


# =========================
# LINEAR REGRESSION
# =========================

# Formula:
# y = mx + b

# x = input
# y = predicted output
# m = slope
# b = intercept


# KEY REMEMBER:
# Feature     -> Input
# Target      -> Output
# Fit         -> Learn
# Predict     -> Prediction
# Regression  -> Number
# Classification -> Category
# Clustering  -> Groups