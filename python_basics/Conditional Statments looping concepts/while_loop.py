# pass      --> do nothing; used as a placeholder

# break     --> stop the loop completely

# continue  --> skip the current loop iteration and go to the next one

# return    --> send a value back from a function

# yield     --> return a value from a generator, one at a time

# if        --> run code when a condition is True

# elif      --> check another condition if the previous one was False

# else      --> run code when all previous conditions are False

# for       --> repeat code for each item in a sequence

# while     --> repeat code while a condition is True

# def       --> create/define a function

# class     --> create a class

# import    --> bring a module/library into your program

# from      --> import something specific from a module

# as        --> give an imported module/value another name

# try       --> try to run code that might cause an error

# except    --> handle an error

# finally   --> run code whether an error happens or not

# raise     --> manually create/throw an error

# assert    --> check that a condition is True

# in        --> check whether a value exists inside something

# not in    --> check whether a value does NOT exist inside something

# is        --> check whether two objects are the same object

# is not    --> check whether two objects are different objects

# and       --> both conditions must be True

# or        --> at least one condition must be True

# not       --> reverse True/False

# True      --> Boolean value meaning yes/true

# False     --> Boolean value meaning no/false

# None      --> means no value / empty value

# lambda    --> create a small anonymous function

# with      --> work with resources and automatically clean them up

# as        --> give a temporary name inside "with" or imports

# global    --> use/modify a variable from the global scope

# nonlocal  --> use/modify a variable from an outer function

# del       --> delete a variable, item, or attribute

# async     --> define asynchronous code

# await     --> wait for an asynchronous operation






